@app.route('/api/subscription/check')
def check_subscription():
    """Public: check whether an email has unlimited access."""
    email = (request.args.get('email') or '').strip().lower()
    if not re.match(r'^[^@\s]+@[^@\s]+\.[^@\s]+$', email):
        return jsonify({'success': False, 'error': 'Invalid email'}), 400
    unlimited = is_unlimited(email)
    return jsonify({
        'success': True,
        'email': email,
        'unlimited': unlimited,
        'plan': 'unlimited' if unlimited else 'free',
    })


# ------------------------------------------------------------------
# Admin API  (requires X-Admin-Email + X-Admin-Token headers)
# ------------------------------------------------------------------

@app.route('/api/admin/whitelist', methods=['GET'])
def admin_list_whitelist():
    denied = require_admin()
    if denied:
        return denied
    entries = _load_whitelist()
    return jsonify({'success': True, 'count': len(entries), 'whitelist': entries})


@app.route('/api/admin/whitelist', methods=['POST'])
def admin_add_whitelist():
    denied = require_admin()
    if denied:
        return denied
    payload = request.get_json(silent=True) or {}
    email = (payload.get('email') or '').strip().lower()
    if not re.match(r'^[^@\s]+@[^@\s]+\.[^@\s]+$', email):
        return jsonify({'success': False, 'error': 'Valid email required'}), 400

    entries = _load_whitelist()
    if is_unlimited(email):
        return jsonify({'success': False, 'error': 'Email already in whitelist'}), 409
    entries.append({
        'email': email,
        'added': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        'added_by': (request.headers.get('X-Admin-Email') or '').strip().lower(),
    })
    _save_whitelist(entries)
    return jsonify({'success': True, 'count': len(entries), 'added': email}), 201


@app.route('/api/admin/whitelist', methods=['DELETE'])
def admin_remove_whitelist():
    denied = require_admin()
    if denied:
        return denied
    email = (request.args.get('email') or '').strip().lower()
    if not email:
        return jsonify({'success': False, 'error': 'email query param required'}), 400

    entries = _load_whitelist()
    new_entries = [e for e in entries if e.get('email', '').lower() != email]
    if len(new_entries) == len(entries):
        return jsonify({'success': False, 'error': 'Email not in whitelist'}), 404
    _save_whitelist(new_entries)
    return jsonify({'success': True, 'count': len(new_entries), 'removed': email})


