# ------------------------------------------------------------------
# Unlimited-access whitelist
# ------------------------------------------------------------------

def _load_whitelist():
    """Read the whitelist file. Format:
    [{"email": "x@y.com", "added": "2026-11-07T00:00:00Z", "added_by": "admin@x.com"}]
    """
    try:
        with open(WHITELIST_FILE, "r") as f:
            data = json.load(f)
        return data if isinstance(data, list) else []
    except (FileNotFoundError, json.JSONDecodeError):
        return []


def _save_whitelist(entries):
    os.makedirs(DATA_DIR, exist_ok=True)
    tmp = WHITELIST_FILE + ".tmp"
    with open(tmp, "w") as f:
        json.dump(entries, f, indent=2)
    os.replace(tmp, WHITELIST_FILE)
    try:
        import pwd, grp
        owner = os.environ.get("CYBERSHIELD_APP_USER", "cybershield")
        os.chown(WHITELIST_FILE, pwd.getpwnam(owner).pw_uid, grp.getgrnam(owner).gr_gid)
    except Exception:
        pass


def is_unlimited(email):
    email = (email or "").strip().lower()
    return any(e.get("email", "").lower() == email for e in _load_whitelist())


def require_admin():
    """Return None if request is authorized as admin, else a 401/403 response."""
    email = (request.headers.get("X-Admin-Email") or "").strip().lower()
    token = request.headers.get("X-Admin-Token") or ""
    if not ADMIN_TOKEN:
        return jsonify({"success": False, "error": "Admin API not configured (set CYBERSHIELD_ADMIN_TOKEN)"}), 503
    if not secrets.compare_digest(token, ADMIN_TOKEN):
        return jsonify({"success": False, "error": "Invalid admin token"}), 401
    if email not in ADMIN_EMAILS:
        return jsonify({"success": False, "error": "Email not authorized"}), 403
    return None


